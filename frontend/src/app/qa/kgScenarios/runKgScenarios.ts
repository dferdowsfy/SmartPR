// KG scenario matrix runner: runs every scenario in ./scenarios and writes
// frontend/test-reports/kg-scenarios.md + .json.
//
//   npm run test:scenarios            # write the report; exit 1 only on harness issues or untriaged findings
//   npm run test:scenarios -- --strict  # exit 1 on any failing scenario
//
// Deterministic: geo facts come from geoContexts.json fixtures parsed by the
// live parsers; no network. The live geo service check is `npm run geo:health`.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { KG_DIR, kgTestName, loadGeoContexts, loadKgScenarios, lintScenario, runAndEvaluate, type Finding, type ScenarioResult } from "./harness.ts";

type Cause = "likely-engine-bug" | "kb-gap" | "likely-wrong-expectation" | "harness-issue";
interface TriageEntry { id: string; kind: string; key: string; cause: Cause; note: string }

const CAUSE_LABEL: Record<Cause, string> = {
  "likely-engine-bug": "Likely engine bug",
  "kb-gap": "KB coverage gap (engine content)",
  "likely-wrong-expectation": "Likely wrong expectation / needs expert",
  "harness-issue": "Harness issue",
};

const FRONTEND = join(KG_DIR, "..", "..", "..", "..");
const OUT_DIR = join(FRONTEND, "test-reports");
const triage: TriageEntry[] = JSON.parse(readFileSync(join(KG_DIR, "triage.json"), "utf8")).entries;

function classify(id: string, f: Finding): { cause: Cause; note: string; triaged: boolean } {
  const t = triage.find((e) => e.id === id && e.kind === f.kind && e.key === f.key);
  if (t) return { cause: t.cause, note: t.note, triaged: true };
  if (f.kind === "harness") return { cause: "harness-issue", note: "Fixture model fact rejected by validateProjectContext.", triaged: false };
  if (f.kind === "gap") return { cause: "kb-gap", note: "No KB requirement models this obligation.", triaged: false };
  if (f.kind === "leak" || f.kind === "duplicate" || f.kind === "questions") return { cause: "likely-engine-bug", note: "Presentation contract violated.", triaged: false };
  if (f.confidence === "verified-in-code") return { cause: "likely-engine-bug", note: "Contradicts a rule/test the expectation was verified against.", triaged: false };
  return { cause: "likely-wrong-expectation", note: "Unverified expectation: expert review decides engine vs. expectation.", triaged: false };
}

const geo = loadGeoContexts();
const scenarios = loadKgScenarios();
const lint = scenarios.flatMap((s) => lintScenario(s, geo));
const results: Array<ScenarioResult & { testName: string; findingsClassified: Array<Finding & { cause: Cause; note: string; triaged: boolean }>; error?: string }> = [];
for (const s of scenarios) {
  try {
    const r = runAndEvaluate(s, geo);
    results.push({ ...r, testName: kgTestName(s), findingsClassified: r.findings.map((f) => ({ ...f, ...classify(s.id, f) })) });
  } catch (e) {
    const f: Finding = { kind: "harness", message: `scenario threw: ${(e as Error).message}` };
    results.push({ id: s.id, title: s.title, matrix: s.matrix, status: "fail", findings: [f], orderingSkipped: [], items: [], questions: [], energyQuestionsUncapped: 0, otherCheckQuestions: [], discardedModelFacts: [], testName: kgTestName(s), findingsClassified: [{ ...f, cause: "harness-issue", note: "Harness crashed.", triaged: false }], error: (e as Error).stack });
  }
}

const pass = results.filter((r) => r.status === "pass").length;
const fail = results.length - pass;
const expectations = scenarios.flatMap((s) => [...s.expect.mustInclude, ...s.expect.mustNotInclude, ...(s.expect.ordering ?? [])]);
const verified = expectations.filter((e) => e.confidence === "verified-in-code").length;

function summarize(by: (r: ScenarioResult) => string) {
  const m = new Map<string, { pass: number; fail: number; ids: string[] }>();
  for (const r of results) {
    const k = by(r);
    const v = m.get(k) ?? { pass: 0, fail: 0, ids: [] };
    if (r.status === "pass") v.pass++; else { v.fail++; v.ids.push(r.id); }
    m.set(k, v);
  }
  return [...m.entries()].sort(([a], [b]) => a.localeCompare(b));
}
const allFindings = results.flatMap((r) => r.findingsClassified.map((f) => ({ id: r.id, ...f })));
const byCause = new Map<Cause, typeof allFindings>();
for (const f of allFindings) byCause.set(f.cause, [...(byCause.get(f.cause) ?? []), f]);

const esc = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");
const md: string[] = [];
md.push("# KG scenario matrix report", "");
md.push(`Generated by \`npm run test:scenarios\` (frontend/${relative(FRONTEND, join(KG_DIR, "runKgScenarios.ts"))}). Deterministic: geo facts are fixtures (\`geoContexts.json\`) parsed by the live layer parsers, with no network calls. The separate live check of the geo services is \`npm run geo:health\`.`, "");
md.push(`**${results.length} scenarios: ${pass} pass, ${fail} fail.** ${expectations.length} expectations: ${verified} verified-in-code, ${expectations.length - verified} needs-expert-review.`, "");
if (lint.length) md.push("## Fixture lint problems", "", ...lint.map((l) => `- ${l}`), "");
md.push("## Findings by likely cause", "");
md.push("| Cause | Findings | Scenarios |", "|---|---|---|");
for (const c of Object.keys(CAUSE_LABEL) as Cause[]) {
  const fs = byCause.get(c) ?? [];
  md.push(`| ${CAUSE_LABEL[c]} | ${fs.length} | ${[...new Set(fs.map((f) => f.id))].join(", ") || "-"} |`);
}
md.push("");
for (const c of Object.keys(CAUSE_LABEL) as Cause[]) {
  const fs = byCause.get(c) ?? [];
  if (!fs.length) continue;
  md.push(`### ${CAUSE_LABEL[c]}`, "");
  for (const f of fs) md.push(`- **${f.id}** [${f.kind}${f.confidence ? `, ${f.confidence}` : ""}] ${esc(f.message)} | ${esc(f.note)}${f.triaged ? "" : " _(untriaged)_"}`);
  md.push("");
}
md.push("## Summary by business type", "", "| Business type | Pass | Fail | Failing |", "|---|---|---|---|");
for (const [k, v] of summarize((r) => r.matrix.businessType)) md.push(`| ${k} | ${v.pass} | ${v.fail} | ${v.ids.join(", ")} |`);
md.push("", "## Summary by location context", "", "| Location context | Pass | Fail | Failing |", "|---|---|---|---|");
for (const [k, v] of summarize((r) => r.matrix.locationContext)) md.push(`| ${k} | ${v.pass} | ${v.fail} | ${v.ids.join(", ")} |`);
md.push("", "## Summary by project type", "", "| Project type | Pass | Fail | Failing |", "|---|---|---|---|");
for (const [k, v] of summarize((r) => r.matrix.projectType)) md.push(`| ${k} | ${v.pass} | ${v.fail} | ${v.ids.join(", ")} |`);
md.push("", "## Per scenario", "");
md.push("| ID | Status | Scenario | Questions | Missing | Unexpected | Ordering | Other |", "|---|---|---|---|---|---|---|---|");
for (const r of results) {
  const k = (kinds: string[]) => r.findings.filter((f) => kinds.includes(f.kind)).map((f) => f.key ?? f.message).join("; ") || "";
  md.push(`| ${r.id} | ${r.status === "pass" ? "PASS" : "**FAIL**"} | ${esc(r.title)} | ${r.questions.length} | ${esc(k(["missing", "gap", "agency", "applicability"]))} | ${esc(k(["unexpected", "duplicate"]))} | ${esc(k(["ordering"]))} | ${esc(k(["questions", "leak", "harness"]))} |`);
}
md.push("", "## Scenario details", "");
for (const r of results) {
  md.push(`### ${r.id}: ${r.title} (${r.status.toUpperCase()})`, "");
  md.push(`Matrix: ${r.matrix.businessType} / ${r.matrix.projectType} / ${r.matrix.locationContext}. CI test name: \`${r.testName}\``, "");
  md.push(`Rendered order: ${r.items.map((i) => `${i.key.replace(/^DOC_/, "")}${i.applicability ? ` (${i.applicability})` : ""}`).join(" > ") || "(none)"}`, "");
  if (r.questions.length) md.push(`Questions (${r.questions.length}): ${r.questions.map(esc).join(" · ")}`, "");
  for (const f of r.findingsClassified) md.push(`- [${f.kind}] ${esc(f.message)}. ${CAUSE_LABEL[f.cause]}: ${esc(f.note)}${f.rationale ? ` Expectation: ${esc(f.rationale)}` : ""}`);
  if (r.orderingSkipped.length) md.push(`- Ordering not evaluated: ${r.orderingSkipped.join("; ")}`);
  if (r.error) md.push("", "```", r.error, "```");
  md.push("");
}

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(join(OUT_DIR, "kg-scenarios.md"), md.join("\n"));
writeFileSync(
  join(OUT_DIR, "kg-scenarios.json"),
  JSON.stringify({ summary: { scenarios: results.length, pass, fail, expectations: expectations.length, verified, lint }, results: results.map((r) => ({ ...r, findings: undefined })) }, null, 2) + "\n"
);
console.log(`KG scenarios: ${pass}/${results.length} pass, ${fail} fail. Report: ${relative(process.cwd(), join(OUT_DIR, "kg-scenarios.md"))}`);
for (const c of Object.keys(CAUSE_LABEL) as Cause[]) console.log(`  ${CAUSE_LABEL[c]}: ${(byCause.get(c) ?? []).length}`);

const untriaged = allFindings.filter((f) => !f.triaged);
const harness = allFindings.filter((f) => f.cause === "harness-issue");
if (untriaged.length) console.log(`\n${untriaged.length} untriaged finding(s) (add to triage.json):\n${untriaged.map((f) => `  ${f.id} ${f.kind} ${f.key ?? ""}: ${f.message}`).join("\n")}`);
const strict = process.argv.includes("--strict");
if (lint.length || harness.length || untriaged.length || (strict && fail)) process.exit(1);
