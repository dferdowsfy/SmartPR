#!/usr/bin/env python3
"""
Build the CSP-safe vector basemap for the SmartPR ChatGPT widget.

ChatGPT renders the widget in a sandboxed iframe with a strict CSP. External
raster tiles made the widget fragile ("Couldn't open …"), so the map ships its
own geometry: the 78 Puerto Rico municipio outlines, shoreline-clipped, drawn as
inline SVG. No network, no image hosts, empty CSP allowlists.

Source (public domain, U.S. Census Bureau):
  Cartographic Boundary 2024 counties, 1:500k (in Puerto Rico, county = municipio)
  https://www2.census.gov/geo/tiger/GENZ2024/shp/cb_2024_us_county_500k.zip

Output: frontend/src/lib/chatgpt/prMapShapes.ts (generated — do not edit)
  Topology-preserving coverage simplification (shared borders stay shared), then
  each ring is Google-polyline encoded at 1e-4 degree precision (~11 m).
  The widget decoder is in frontend/src/lib/chatgpt/widget.ts.

Usage:
  pip install pyshp shapely   # shapely >= 2.1 (coverage_simplify)
  curl -O <zip URL above>; unzip cb_2024_us_county_500k.zip
  python3 frontend/scripts/build-chatgpt-map-shapes.py <dir with the unzipped files>
"""

import json
import os
import sys

import shapefile  # pyshp
import shapely
from shapely.geometry import MultiPolygon, Polygon, shape

TOLERANCE_DEG = 0.002  # coverage simplification tolerance
MIN_AREA_DEG2 = 2e-5  # drop islets smaller than ~0.25 km² (Mona, Desecheo, Culebra, Vieques stay)
PRECISION = 1e4


def enc_value(v):
    v = ~(v << 1) if v < 0 else (v << 1)
    out = []
    while v >= 0x20:
        out.append(chr((0x20 | (v & 0x1F)) + 63))
        v >>= 5
    out.append(chr(v + 63))
    return "".join(out)


def encode_ring(coords):
    pts = [(round(lat * PRECISION), round(lng * PRECISION)) for lng, lat in coords]
    if len(pts) > 1 and pts[0] == pts[-1]:
        pts = pts[:-1]  # implicit close
    out, plat, plng = [], 0, 0
    for lat, lng in pts:
        if (lat, lng) == (plat, plng) and out:
            continue
        out.append(enc_value(lat - plat) + enc_value(lng - plng))
        plat, plng = lat, lng
    return "".join(out)


def polys(g):
    return [g] if g.geom_type == "Polygon" else list(g.geoms)


def filt(g):
    keep = [Polygon(p.exterior, [i for i in p.interiors if Polygon(i).area >= MIN_AREA_DEG2]) for p in polys(g) if p.area >= MIN_AREA_DEG2]
    return keep[0] if len(keep) == 1 else MultiPolygon(keep)


def main(src_dir):
    reader = shapefile.Reader(os.path.join(src_dir, "cb_2024_us_county_500k"))
    recs = [(sr.record["NAME"], shape(sr.shape.__geo_interface__)) for sr in reader.iterShapeRecords() if sr.record["STATEFP"] == "72"]
    recs.sort(key=lambda r: r[0])
    names = [n for n, _ in recs]
    geoms = shapely.coverage_simplify([filt(g) for _, g in recs], TOLERANCE_DEG)
    munis = []
    for name, g in zip(names, geoms):
        lab = g.representative_point() if g.geom_type == "Polygon" else max(polys(g), key=lambda p: p.area).representative_point()
        rings = []
        for p in polys(g):
            rings.append(encode_ring(p.exterior.coords))
            rings.extend(encode_ring(i.coords) for i in p.interiors)
        munis.append([name, round(lab.x, 4), round(lab.y, 4), " ".join(r for r in rings if r)])
    out = os.path.join(os.path.dirname(__file__), "..", "src", "lib", "chatgpt", "prMapShapes.ts")
    body = ",\n".join("  " + json.dumps(m, ensure_ascii=False) for m in munis)
    with open(out, "w", encoding="utf-8") as fh:
        fh.write(
            "// GENERATED by frontend/scripts/build-chatgpt-map-shapes.py — do not edit.\n"
            "// Puerto Rico municipio outlines for the ChatGPT widget's CSP-safe vector map.\n"
            "// Source: U.S. Census Bureau Cartographic Boundary 2024 counties 1:500k (public domain).\n"
            f"// Coverage-simplified (tolerance {TOLERANCE_DEG}°), rings Google-polyline encoded at 1e-4°.\n"
            "// [name, labelLng, labelLat, \"ring ring …\"] — even-odd fill.\n"
            "export const PR_MAP_SOURCE = \"U.S. Census Bureau, Cartographic Boundary 2024\";\n"
            "export const PR_MUNICIPIO_SHAPES: ReadonlyArray<readonly [string, number, number, string]> = [\n"
            f"{body},\n];\n"
        )
    print(f"wrote {out}: {len(munis)} municipios, {sum(len(m[3]) for m in munis)} encoded chars")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else ".")
